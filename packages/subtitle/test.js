// ── real-world fixtures ──

t('SRT — real-world: BOM, CRLF, missing trailing blank line', () => {
	let raw = '﻿1\r\n00:00:00,500 --> 00:00:02,000\r\nHello\r\n\r\n2\r\n00:00:02,500 --> 00:00:04,000\r\nWorld'
	let subs = parse(raw)
	is(subs.format, 'srt')
	is(subs.cues.length, 2)
	is(subs.cues[0].text, 'Hello')
	almost(subs.cues[0].start, 0.5, 1e-9)
	is(subs.cues[1].text, 'World')
	almost(subs.cues[1].end, 4, 1e-9)
})

t('VTT — real-world: NOTE, STYLE, <v> voice tags, inline timestamps', () => {
	let raw = [
		'WEBVTT', '',
		'NOTE this file was generated by a test', '',
		'STYLE', '::cue { color: yellow; }', '',
		'1',
		'00:00:00.000 --> 00:00:02.000',
		'<v Alice>Hi <00:00:00.500>there <00:00:01.200>friend</v>', '',
	].join('\n')
	let subs = parse(raw)
	is(subs.cues.length, 1)
	is(subs.cues[0].id, '1')
	is(subs.cues[0].text, 'Hi there friend')
	is(subs.cues[0].words.length, 3)
	almost(subs.cues[0].words[1].start, 0.5, 1e-9)
	almost(subs.cues[0].words[2].end, 2, 1e-9)
})

t('LRC — real-world: player export with [offset:-200] and repeated chorus', () => {
	let raw = [
		'[ti:Test Song]',
		'[ar:Test Artist]',
		'[offset:-200]',
		'[00:12.34]First line',
		'[00:15.00][00:45.00]Chorus line',
		'[00:18.00]Last line',
	].join('\n')
	let subs = parse(raw)
	is(subs.meta.ti, 'Test Song')
	is(subs.meta.offset, '-200')
	is(subs.cues.length, 4)
	// offset -200ms: "+" plays sooner (spec) => actual time = raw - offset = raw + 0.2s
	almost(subs.cues[0].start, 12.34 + 0.2, 1e-9)
	is(subs.cues[1].text, 'Chorus line')
	is(subs.cues[3].text, 'Chorus line') // repeat at 00:45.00, sorted after the 00:18 line
})

t('TTML — real-world: broadcaster frameRate + frame notation + offset-time', () => {
	let raw = `<?xml version="1.0" encoding="UTF-8"?>
<tt:tt xmlns:tt="http://www.w3.org/ns/ttml" xmlns:ttp="http://www.w3.org/ns/ttml#parameter" ttp:frameRate="25">
  <tt:body>
    <tt:div>
      <tt:p begin="00:00:01:12" end="00:00:04:00">Broadcast line one</tt:p>
      <tt:p begin="4.5s" end="7s">Offset-time line</tt:p>
    </tt:div>
  </tt:body>
</tt:tt>`
	let subs = parse(raw, 'ttml')
	is(subs.cues.length, 2)
	almost(subs.cues[0].start, 1 + 12 / 25, 1e-9) // 12 frames @ 25fps
	almost(subs.cues[0].end, 4, 1e-9)
	is(subs.cues[0].text, 'Broadcast line one')
	almost(subs.cues[1].start, 4.5, 1e-9)
	almost(subs.cues[1].end, 7, 1e-9)
})

t('parse — auto-detects format', () => {
	is(parse('WEBVTT\n\n').format, 'vtt')
	is(parse('<?xml version="1.0"?><tt xmlns="http://www.w3.org/ns/ttml"><body><div></div></body></tt>').format, 'ttml')
	is(parse('[00:01.00]hi').format, 'lrc')
	is(parse('1\n00:00:01,000 --> 00:00:02,000\nhi\n').format, 'srt')
})

// ── fromWords ──

t('fromWords — 60 words w/ punctuation + one 2s gap: Netflix-style limits held', () => {
	let sentence = 'the quick brown fox jumps over the lazy dog and runs away very fast today'.split(' ')
	let words = []
	let time = 0
	for (let i = 0; i < 60; i++) {
		let text = sentence[i % sentence.length] + ((i + 1) % 8 === 0 ? '.' : '')
		let dur = 0.25 + (i % 3) * 0.05
		let start = time, end = start + dur
		words.push({ start, end, text })
		time = end + (i === 29 ? 2.0 : 0.15) // one 2s gap right after word 29
	}
	let cues = fromWords(words)
	ok(cues.length > 1, 'segments into multiple cues')
	for (let c of cues) {
		ok(c.end - c.start <= 6 + 1e-9, `cue duration <= 6s (got ${c.end - c.start})`)
		for (let line of c.text.split('\n')) ok(line.length <= 42, `line <= 42 chars ("${line}", ${line.length})`)
	}
	for (let i = 1; i < cues.length; i++) ok(cues[i].start >= cues[i - 1].end - 1e-9, 'monotonic, non-overlapping')
	let gapEnd = words[29].end, gapStart = words[30].start
	let splitAtGap = cues.some((c, i) => i > 0 && Math.abs(cues[i - 1].end - gapEnd) < 1e-9 && Math.abs(c.start - gapStart) < 1e-9)
	ok(splitAtGap, 'breaks exactly at the 2s gap')
})

t('fromWords — empty input yields empty cues', () => {
	is(fromWords([]), [])
})

t('fromWords — throws on malformed items', () => {
	throws(() => fromWords([{ start: 0, end: 1 }]), /missing text\/word/)
	throws(() => fromWords([{ text: 'x', start: 1, end: 0 }]), /invalid start\/end/)
})

// ── shift / scale / project ──

t('shift/scale — exact, cover both Cue[] and Subtitles forms', () => {
	let cues = [{ start: 1, end: 2, text: 'a', words: [{ start: 1, end: 1.5, text: 'a' }] }]
	let shifted = shift(cues, 0.5)
	is(shifted[0].start, 1.5); is(shifted[0].end, 2.5)
	is(shifted[0].words[0].start, 1.5); is(shifted[0].words[0].end, 2)

	let scaled = scale(cues, 2)
	is(scaled[0].start, 2); is(scaled[0].end, 4)
	is(scaled[0].words[0].start, 2); is(scaled[0].words[0].end, 3)

	let subs = { format: 'srt', cues }
	let shiftedSubs = shift(subs, 1)
	is(shiftedSubs.format, 'srt')
	is(shiftedSubs.cues[0].start, 2)
	is(cues[0].start, 1, 'inputs are not mutated')
})

t('project — desilence-style map: drops cues fully inside removed spans, warps the rest', () => {
	// input [0,2] kept 1:1; [2,5] removed (collapses to output point 2); input [5,8] kept -> output [2,5]
	let map = [{ from: 0, to: 0 }, { from: 2, to: 2 }, { from: 5, to: 2 }, { from: 8, to: 5 }]
	let cues = [
		{ start: 0.5, end: 1.5, text: 'kept-early' },  // fully inside kept [0,2]
		{ start: 3, end: 4, text: 'dropped' },          // fully inside removed [2,5]
		{ start: 6, end: 7, text: 'kept-late' },        // inside kept [5,8], shifted -3
	]
	let out = project(cues, map)
	is(out.length, 2)
	is(out[0].text, 'kept-early')
	almost(out[0].start, 0.5, 1e-9); almost(out[0].end, 1.5, 1e-9)
	is(out[1].text, 'kept-late')
	almost(out[1].start, 3, 1e-9); almost(out[1].end, 4, 1e-9)
})

// ── malformed input / edge cases ──

t('parse — throws with a line number for a bad SRT timestamp', () => {
	let bad = '1\n00:00:01;000 --> 00:00:03,500\ntext\n'
	throws(() => parse(bad, 'srt'), /line 2/)
})

t('parse — VTT throws without a WEBVTT header', () => {
	throws(() => parse('1\n00:00:00.000 --> 00:00:01.000\nhi', 'vtt'), /WEBVTT/)
})

t('parse — TTML throws without a <tt> root', () => {
	throws(() => parse('<foo></foo>', 'ttml'), /<tt>/)
})

t('parse/write — throw on an unknown format', () => {
	throws(() => parse('x', 'ass'))
	throws(() => write([], 'ass'))
})

t('parse — empty input yields empty cues', () => {
	is(parse('').cues, [])
	is(parse('', 'vtt').cues, [])
	is(parse('   \n  ').cues, [])
})

t('LRC — precision option controls fraction digits', () => {
	let out = write({ format: 'lrc', cues: [{ start: 1.234, end: 6.234, text: 'x' }] }, 'lrc', { precision: 3 })
	ok(out.includes('[00:01.234]'), 'writes millisecond precision when opts.precision=3')
})
